"""Open this file in your IDE and press Run.

It translates every example in examples/, writes the C++ to examples/cpp_out/, compiles it,
checks it against Python on hand-picked and random inputs, times both, and writes the
results table to examples/RESULTS.md.

If no C++ compiler is found it still translates (so you can read the C++), and tells you
how to install one. On Windows you can point COMPILER at a g++.exe directly, e.g.
COMPILER = r"C:\\winlibs\\mingw64\\bin\\g++.exe".
"""
from pathlib import Path

from qtrans import translate_file, verify_file

COMPILER = None          # None = search PATH (g++, clang++, cl), or give a full path
RANDOM_CASES = 200       # random inputs per function, on top of the hand-picked ones
BENCHMARK = True

HERE = Path(__file__).resolve().parent
EXAMPLES = ["black_scholes", "implied_vol", "futures_options", "bonds", "exotics",
            "portfolio", "lattice_pde", "risk", "monte_carlo"]


def main():
    out = HERE / "examples" / "cpp_out"
    for name in EXAMPLES + ["not_yet_supported"]:
        r = translate_file(HERE / "examples" / f"{name}.py", out)
        print(r.report.to_text(), "\n")
    print(f"C++ written to {out}\n")

    rows = []
    for name in EXAMPLES:
        try:
            rep = verify_file(HERE / "examples" / f"{name}.py", n_random=RANDOM_CASES, bench=BENCHMARK,
                              compiler=COMPILER, build_dir=HERE / "build" / name)
        except RuntimeError as e:
            print(e)
            return
        print(rep.to_text(), "\n")
        for f in rep.functions:
            rows.append((name, f, rep))

    lines = ["# Verification results", "",
             "Generated by `run_examples.py`. Python vs compiled C++ on the same inputs; "
             "`known` = Python raised a float error (ZeroDivisionError, OverflowError, math "
             "domain error) where IEEE-754 C++ returns inf/NaN. Max rel err / ULP exclude "
             "values within atol (1e-13) of each other. Timings are per call on one input; "
             "one scalar `scipy.stats.norm.cdf` call costs roughly 25-30 µs in Python against roughly 100-150 ns for "
             "`scipy.special.ndtr` (see `tools/measure_library_ulps.py`), so for functions using "
             "`norm` most of the speed-up is SciPy's per-call overhead, not compilation.", "",
             "| module | function | cases | match | ill-cond | known | mismatch | max rel err | max ULP | Python ns | C++ ns | speed-up |",
             "|---|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|"]
    for mod, f, rep in rows:
        speed = f"{f.py_ns / f.cpp_ns:,.0f}x" if f.cpp_ns else ""
        py = f"{f.py_ns:,.0f}" if f.py_ns else ""
        cc = f"{f.cpp_ns:,.1f}" if f.cpp_ns else ""
        lines.append(f"| {mod} | `{f.name}` | {len(f.cases)} | {f.count('match')} | {f.count('illcond')} | {f.count('known')} | "
                     f"{f.count('mismatch')} | {f.max_rel_err:.1e} | {f.max_ulps:,} | {py} | {cc} | {speed} |")
    total = sum(f.count("mismatch") for _, f, _ in rows)
    lines += ["", f"**Total mismatches: {total}.** Compiler: {rows[0][2].compiler}, flags: "
              "`-std=c++17 -O2 -Wall -Wextra -Wpedantic -Wshadow -Wconversion -Wdouble-promotion "
              "-ffp-contract=off`; warnings in generated code: "
              f"{sum(len(r.warnings) for r in {id(r): r for _, _, r in rows}.values())}."]
    (HERE / "examples" / "RESULTS.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Results table written to {HERE / 'examples' / 'RESULTS.md'}")


if __name__ == "__main__":
    main()
