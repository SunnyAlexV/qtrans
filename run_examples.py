"""Open this file in your IDE and press Run.

It translates every example in examples/, writes the C++ to examples/cpp_out/, compiles it,
checks it against Python on hand-picked and random inputs, times both, and writes the
results table to examples/RESULTS.md.

`python run_examples.py --check` writes nothing: it runs the same checks (without timing) and
fails if anything deterministic differs from the committed examples/RESULTS.md and
examples/cpp_out/ (CI runs it on the reference platform, where those files come from).

If no C++ compiler is found it still translates (so you can read the C++), and tells you
how to install one. On Windows you can point COMPILER at a g++.exe directly, e.g.
COMPILER = r"C:\\winlibs\\mingw64\\bin\\g++.exe".
"""
import sys
import tempfile
from pathlib import Path

from qtrans import translate_file, translate_project, verify_file

COMPILER = None          # None = search PATH (g++, clang++, cl), or give a full path
RANDOM_CASES = 200       # random inputs per function, on top of the hand-picked ones
BENCHMARK = True

HERE = Path(__file__).resolve().parent
EXAMPLES = ["black_scholes", "implied_vol", "futures_options", "bonds", "exotics",
            "portfolio", "lattice_pde", "risk", "monte_carlo", "black_litterman_app", "instruments"]


def _det(line):
    """The columns of a RESULTS.md row that don't depend on timing."""
    c = [x.strip() for x in line.split("|")[1:-1]]
    return tuple(c[:9])


def main(check=False):
    committed = HERE / "examples" / "cpp_out"
    out = Path(tempfile.mkdtemp(prefix="qtrans_check_")) / "cpp_out" if check else committed
    for name in EXAMPLES + ["not_yet_supported"]:
        r = translate_file(HERE / "examples" / f"{name}.py", out)
        print(r.report.to_text(), "\n")
    # the app's own modules, as a project: one header per module (examples/bl_app)
    proj = translate_project(HERE / "examples" / "bl_app", out / "bl_app")
    for m in proj.order:
        print(proj.modules[m].report.to_text(), "\n")
    print(f"C++ written to {out}\n")

    rows = []
    for name in EXAMPLES:
        try:
            rep = verify_file(HERE / "examples" / f"{name}.py", n_random=RANDOM_CASES, bench=BENCHMARK and not check,
                              compiler=COMPILER, build_dir=HERE / "build" / name)
        except RuntimeError as e:
            print(e)
            return 1
        print(rep.to_text(), "\n")
        for f in rep.functions:
            rows.append((name, f, rep))

    lines = ["# Verification results", "",
             "Generated by `run_examples.py`. Python vs compiled C++ on the same inputs; "
             "`known` = Python raised a float error (ZeroDivisionError, OverflowError, math "
             "domain error) where IEEE-754 C++ returns inf/NaN. Max rel err / ULP exclude "
             "values within atol (1e-13) of each other. Timings are per call on one input; "
             "one scalar `scipy.stats.norm.cdf` call costs roughly 25-30 µs in Python against roughly 100-150 ns for "
             "`scipy.special.ndtr` (see `tools/measure_library_ulps.py`), so for functions using "
             "`norm` most of the speed-up is SciPy's per-call overhead, not compilation.", "",
             "| module | function | cases | match | ill-cond | known | mismatch | max rel err | max ULP | Python ns | C++ ns | speed-up |",
             "|---|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|"]
    for mod, f, rep in rows:
        speed = f"{f.py_ns / f.cpp_ns:,.0f}x" if f.cpp_ns else ""
        py = f"{f.py_ns:,.0f}" if f.py_ns else ""
        cc = f"{f.cpp_ns:,.1f}" if f.cpp_ns else ""
        lines.append(f"| {mod} | `{f.name}` | {len(f.cases)} | {f.count('match')} | {f.count('illcond')} | {f.count('known')} | "
                     f"{f.count('mismatch')} | {f.max_rel_err:.1e} | {f.max_ulps:,} | {py} | {cc} | {speed} |")
    total = sum(f.count("mismatch") for _, f, _ in rows)
    lines += ["", f"**Total mismatches: {total}.** Compiler: {rows[0][2].compiler}, flags: "
              "`-std=c++17 -O2 -Wall -Wextra -Wpedantic -Wshadow -Wconversion -Wdouble-promotion "
              "-ffp-contract=off`; warnings in generated code: "
              f"{sum(len(r.warnings) for r in {id(r): r for _, _, r in rows}.values())}.",
              "", _audit_line(rows),
              "", f"Platform: {rows[0][2].environment}. Results using the C library's or NumPy's own "
              "`exp`, `log`, `pow` or `erf` (and the ULP counts and speeds) hold for this platform; "
              "other platforms' results are in CI (`.github/workflows/tests.yml`)."]
    results = HERE / "examples" / "RESULTS.md"
    if check:
        return _check(lines, results, out, committed)
    results.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Results table written to {results}")
    return 0


def _audit_line(rows) -> str:
    """The linear-algebra audit over every example (see qtrans_arrays.hpp)."""
    cases = [(f, c) for _, f, _ in rows for c in f.cases if c.audit is not None and c.audit[0] > 0]
    if not cases:
        return "numpy.linalg audit: no example calls numpy.linalg."
    f, c = max(cases, key=lambda t: t[1].audit[1])
    ops = sum(c.audit[0] for _, c in cases)
    return (f"**numpy.linalg audit:** {len(cases):,} cases ran {ops:,} `numpy.linalg` operations (each measures its "
            f"residual against the bound for a backward-stable algorithm); the largest was {c.audit[1]:.3f} of "
            f"its bound ({c.audit[2]}, in `{f.name}`). Unstable results: "
            f"{sum(1 for _, c in cases if c.unstable)}.")


def _check(lines, results, out, committed) -> int:
    """Counts must reproduce exactly everywhere. The max rel err / ULP columns too, except for
    functions using matrix products or numpy.linalg: OpenBLAS picks its kernels for the CPU it
    runs on, so NumPy's own rounding there (and so the distance to it) changes with the CPU."""
    from qtrans.verify import linalg_functions
    blas = {(name, f) for name in EXAMPLES for f in linalg_functions([HERE / "examples" / f"{name}.py"])}
    rows = lambda ls: [_det(x) for x in ls if x.startswith("| ") and not x.startswith("| module")]
    new, old = rows(lines), rows(results.read_text(encoding="utf-8").splitlines())

    def key(r):
        return r[:7] if (r[0], r[1].strip("`")) in blas else r
    bad = [f"  committed {o}\n  now       {n}" for o, n in zip(old, new) if key(o) != key(n)]
    if len(new) != len(old):
        bad.append(f"  {len(old)} rows committed, {len(new)} now")
    for f in sorted(out.rglob("*")):
        if f.is_file():
            c = committed / f.relative_to(out)
            if not c.exists() or c.read_text(encoding="utf-8") != f.read_text(encoding="utf-8"):
                bad.append(f"  examples/cpp_out/{f.relative_to(out).as_posix()} differs from the committed one")
    if bad:
        print("examples/RESULTS.md or examples/cpp_out/ don't reproduce:\n" + "\n".join(bad))
        return 1
    print(f"OK: {len(new)} rows of examples/RESULTS.md and every header in examples/cpp_out/ reproduce "
          f"({sum((r[0], r[1].strip('`')) in blas for r in new)} use BLAS / LAPACK: counts only)")
    return 0


if __name__ == "__main__":
    sys.exit(main(check="--check" in sys.argv[1:]))
