"""Build the Python bindings of every example, check them against Python and time both.

    python tools/bind_examples.py [--cases N]

Writes examples/BINDINGS.md. Timings are end to end from Python: argument conversion,
the call, and the conversion of the result back, against the Python function itself.
"""
from __future__ import annotations

import argparse
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from qtrans.bind import _fmt_ns, check_bindings  # noqa: E402

FILES = ["black_scholes", "implied_vol", "futures_options", "bonds", "exotics", "portfolio",
         "lattice_pde", "risk", "monte_carlo", "black_litterman_app", "instruments"]


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--cases", type=int, default=200)
    args = ap.parse_args(argv)
    rows, totals = [], {"functions": 0, "cases": 0, "mismatch": 0, "classes": 0}
    for name in FILES:
        build = Path(tempfile.mkdtemp(prefix=f"qtrans_bind_{name}_"))
        r = check_bindings(ROOT / "examples" / f"{name}.py", n_random=args.cases, bench=True, build_dir=build)
        print(r.to_text(), "\n", flush=True)
        totals["functions"] += len(r.extension.binder.bound)
        totals["classes"] += len(r.extension.binder.bound_classes)
        for c in r.checks:
            totals["cases"] += c.cases
            totals["mismatch"] += c.outcomes.get("mismatch", 0)
            if c.kind != "function":
                continue
            best = min((x for x in (c.cpp_ns, c.cpp_obj_ns) if x), default=None)
            rows.append(f"| {name} | `{c.name}` | {c.cases} | {c.outcomes.get('match', 0)} | "
                        f"{c.outcomes.get('known', 0)} | {c.outcomes.get('illcond', 0)} | "
                        f"{c.outcomes.get('mismatch', 0)} | "
                        + (f"{_fmt_ns(c.py_ns)} | {_fmt_ns(best)} | {c.py_ns / best:.1f}x |" if best and c.py_ns
                           else "| | |"))
    md = ["# Python bindings of the examples",
          "",
          "Generated by `tools/bind_examples.py`. Each module was compiled with `qtrans bind` and every "
          "function, method and constructor was run through the compiled module and through Python on "
          "the same inputs (with your Python objects, and again with compiled ones), comparing results, "
          "in-place changes, generator states and exceptions.",
          "",
          f"**{totals['functions']} functions and {totals['classes']} classes, {totals['cases']:,} cases, "
          f"{totals['mismatch']} mismatches.**",
          "",
          "Times are per call from Python, end to end (arguments converted in, result converted back), "
          "on the same representative input as `examples/RESULTS.md`; they vary between runs.",
          "",
          "| Module | Function | Cases | Match | Known | Ill-cond | Mismatch | Python | Compiled | Speed-up |",
          "|---|---|---:|---:|---:|---:|---:|---:|---:|---:|"] + rows
    (ROOT / "examples" / "BINDINGS.md").write_text("\n".join(md) + "\n", encoding="utf-8")
    print(f"wrote examples/BINDINGS.md: {totals}")
    return 0 if totals["mismatch"] == 0 else 1


if __name__ == "__main__":
    sys.exit(main())
