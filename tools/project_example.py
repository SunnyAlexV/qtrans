"""Verify and bind the real app's modules as one project, and write examples/bl_app/RESULTS.md.

    python tools/project_example.py [--cases N] [--no-bind]

examples/bl_app holds four files of the Black-Litterman app (bl_config, bl_core,
bl_inference, bl_backtest) exactly as in the app, with type hints added to the functions
qtrans translates (and one import line for them). This checks that claim against the app's
own repository when it is available next to this one, then verifies every module (one C++
driver for all four) and, with pybind11 installed, builds and checks the bindings.
"""
from __future__ import annotations

import argparse
import ast
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from qtrans import verify_project  # noqa: E402

APP = ROOT / "examples" / "bl_app"
MODULES = ["bl_config", "bl_core", "bl_inference", "bl_backtest"]


def same_bodies(original: Path, ours: Path) -> tuple[int, int]:
    """-> (functions compared, functions whose bodies differ) between the app's file and ours."""
    a = {f.name: f for f in ast.parse(original.read_text(encoding="utf-8")).body if isinstance(f, ast.FunctionDef)}
    b = {f.name: f for f in ast.parse(ours.read_text(encoding="utf-8")).body if isinstance(f, ast.FunctionDef)}
    differ = sum(ast.dump(ast.Module(a[n].body, [])) != ast.dump(ast.Module(b[n].body, [])) for n in a)
    return len(a), differ + len(set(a) ^ set(b))


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--cases", type=int, default=200)
    ap.add_argument("--no-bind", action="store_true")
    ap.add_argument("--app", default=str(ROOT.parent / "Black-Litterman-model"),
                    help="the app's repository, to check the files are unchanged but for type hints")
    args = ap.parse_args(argv)

    lines = ["# The Black-Litterman app as a project", "",
             "Generated by `tools/project_example.py`. The four modules in this folder are the app's own "
             "files with type hints added; qtrans translates them as one project (bl_core and bl_backtest "
             "star-import bl_config, bl_backtest star-imports bl_core), compiles one C++ driver for all "
             "of them, and checks every translated function against Python. Realistic inputs are in "
             "`qtrans_cases.py`.", ""]
    app = Path(args.app)
    if (app / "bl_core.py").exists():
        rows = []
        for m in MODULES:
            n, differ = same_bodies(app / f"{m}.py", APP / f"{m}.py")
            rows.append(f"{m}: {n} functions, {differ} with a different body")
        lines += ["Compared with the app's repository (function bodies, by syntax tree): " + "; ".join(rows) + ".", ""]
        print("\n".join(rows))

    rep = verify_project(APP, n_random=args.cases, bench=True, all_modules=True,
                         build_dir=Path(tempfile.mkdtemp(prefix="qtrans_blapp_")))
    print(rep.to_text())
    translated = sum(len(r.translation.report.translated) for r in rep.modules.values())
    total = sum(len(r.translation.report.functions) for r in rep.modules.values())
    cases = sum(len(f.cases) for r in rep.modules.values() for f in r.functions)
    lines += [f"**{translated} of {total} functions translated; {cases:,} cases compared, "
              f"{len(rep.mismatches)} mismatches.** The others are refused with a reason (most have no "
              "type hints because they work on pandas objects, call `scipy.optimize`, or format text).", "",
              "| module | function | cases | match | ill-cond | known | mismatch | max rel err | Python ns | C++ ns |",
              "|---|---|---:|---:|---:|---:|---:|---:|---:|---:|"]
    for m, r in rep.modules.items():
        for f in r.functions:
            lines.append(f"| {m} | `{f.name}` | {len(f.cases)} | {f.count('match')} | {f.count('illcond')} | "
                         f"{f.count('known')} | {f.count('mismatch')} | {f.max_rel_err:.1e} | "
                         f"{f.py_ns:,.0f} | {f.cpp_ns:,.1f} |")
    ok = rep.ok
    if not args.no_bind:
        from qtrans.bind import check_bindings
        b = check_bindings(APP, n_random=args.cases, bench=True, all_modules=True,
                           build_dir=Path(tempfile.mkdtemp(prefix="qtrans_blapp_bind_")))
        print(b.to_text())
        bcases = sum(c.cases for c in b.checks)
        lines += ["", f"**Python bindings** (`qtrans bind examples/bl_app`: one extension, `bl_app_cpp`, a "
                      f"submodule per module): {len(b.extension.bound)} functions, {bcases:,} cases, "
                      f"{b.mismatches} mismatches.", "",
                  "| function | cases | match | known | ill-cond | mismatch | Python | compiled |",
                  "|---|---:|---:|---:|---:|---:|---:|---:|"]
        from qtrans.bind import _fmt_ns
        for c in b.checks:
            best = min((x for x in (c.cpp_ns, c.cpp_obj_ns) if x), default=None)
            lines.append(f"| `{c.name}` | {c.cases} | {c.outcomes.get('match', 0)} | {c.outcomes.get('known', 0)} | "
                         f"{c.outcomes.get('illcond', 0)} | {c.outcomes.get('mismatch', 0)} | "
                         + (f"{_fmt_ns(c.py_ns)} | {_fmt_ns(best)} |" if best and c.py_ns else "| |"))
        ok = ok and b.ok
    (APP / "RESULTS.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {APP / 'RESULTS.md'}")
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
