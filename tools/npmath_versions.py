"""Runs tools/npmath_check.py under several NumPy releases and CPU settings, and writes the table.

    python tools/npmath_versions.py PYTHON [PYTHON ...] [--n 200000] [--out docs/NUMPY_MATHS.md]

Each PYTHON is an interpreter with one NumPy release installed (for example, environments made
with `uv venv` and `uv pip install numpy==X`). Each is run three times on this machine: as it is,
with NumPy's AVX-512 code switched off (as on an AVX2 machine), and with AVX2 switched off too,
through NumPy's own NPY_DISABLE_CPU_FEATURES, which the C++ honours the same way.
"""
import argparse
import json
import os
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

PROBE = r"""
import json, sys
sys.path.insert(0, %r)
from qtrans import npmath_check as c
r = c.check(n=%d, verbose=False)
import numpy, platform
print(json.dumps({"numpy": numpy.__version__, "python": platform.python_version(), "paths": r["paths"][1],
                  "want": r["paths"][0], "cases": r["cases"], "failures": r["failures"]}))
"""


def disable_names(version: str, level: str) -> str:
    major, minor = (int(x) for x in version.split(".")[:2])
    v4 = "AVX512F AVX512CD AVX512_KNL AVX512_KNM AVX512_SKX AVX512_CLX AVX512_CNL AVX512_ICL AVX512_SPR"
    if (major, minor) >= (2, 4):
        v4 = "X86_V4"
    if level == "avx2":
        return v4
    return v4 + (" X86_V3" if (major, minor) >= (2, 4) else " AVX2 FMA3 F16C")


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("pythons", nargs="+")
    ap.add_argument("--n", type=int, default=200_000)
    ap.add_argument("--out", default=str(ROOT / "docs" / "NUMPY_MATHS.md"))
    a = ap.parse_args(argv)
    rows, total, fails = [], 0, []
    for py in a.pythons:
        ver = subprocess.run([py, "-c", "import numpy; print(numpy.__version__)"], capture_output=True, text=True).stdout.strip()
        for level in ("native", "avx2", "baseline"):
            env = dict(os.environ, PYTHONPATH=str(ROOT))
            if level != "native":
                env["NPY_DISABLE_CPU_FEATURES"] = disable_names(ver, level)
            p = subprocess.run([py, "-c", PROBE % (str(ROOT), a.n)], capture_output=True, text=True, env=env)
            if p.returncode != 0 or not p.stdout.strip():
                fails.append(f"NumPy {ver} ({level}): the check did not run: {p.stderr[-500:]}")
                continue
            r = json.loads(p.stdout.strip().splitlines()[-1])
            exact = [c for c in r["cases"] if c[3]]
            n_exact = sum(c[1] for c in exact)
            total += n_exact
            fails += [f"NumPy {ver} ({level}): {f}" for f in r["failures"]]
            own = {k: v for k, v in r["paths"].items() if k != "numpy_version" and v != "libm"}
            rows.append((ver, level, r["python"], own, n_exact, sum(c[2] for c in exact), len(r["failures"])))
            print(f"NumPy {ver:7s} {level:8s} {len(own):2d} functions NumPy's own code, {n_exact:>10,} values compared, "
                  f"{sum(c[2] for c in exact)} differ, {len(r['failures'])} failures", flush=True)
    groups = {}
    for ver, level, py, own, n, bad, nf in rows:
        groups.setdefault((level, json.dumps(own, sort_keys=True)), []).append(ver)
    L = ["# NumPy's float64 maths, release by release", "",
         "Generated by `tools/npmath_versions.py` (each NumPy release run through `tools/npmath_check.py`).",
         "For each release and CPU setting: which functions NumPy computes with its own code on this machine",
         "(the rest it leaves to the C library), and how many values the C++ runtime (`qtrans_npmath.hpp`)",
         "was compared with NumPy on, bit for bit. *avx2* and *baseline* are this machine with NumPy's AVX-512",
         "(and AVX2) code switched off by `NPY_DISABLE_CPU_FEATURES`, which the C++ follows as NumPy does.", "",
         "| NumPy | CPU | Python | Functions NumPy runs its own code for | Values compared | Differ | Wrong choices |",
         "|---|---|---|---|---:|---:|---:|"]
    for ver, level, py, own, n, bad, nf in rows:
        kinds = {}
        for k, v in sorted(own.items()):
            kinds.setdefault(v, []).append(k)
        desc = "; ".join(f"{v}: {', '.join(ks)}" for v, ks in sorted(kinds.items())) or "none (the C library)"
        L.append(f"| {ver} | {level} | {py} | {desc} | {n:,} | {bad} | {nf} |")
    L += ["", f"{total:,} values compared in all; {sum(r[5] for r in rows)} differ; {len(fails)} failures.", ""]
    if fails:
        L += ["## Failures", ""] + [f"- {f}" for f in fails] + [""]
    Path(a.out).write_text("\n".join(L), encoding="utf-8")
    print(f"wrote {a.out}")
    return 1 if fails else 0


if __name__ == "__main__":
    sys.exit(main())
